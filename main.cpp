#include <iostream>
#include "Vehicle.h"

using namespace std;

/**
 * @brief [17] Главная функция программы.
 * Создаётся не менее трёх объектов одного класса.
 * [18] Для создания объектов используются разные конструкторы.
 * [19] Проверяется независимость состояния объектов.
 * [20] Основная программа находится в отдельном файле main.cpp.
 * [14] В программе проверяются следующие условия корректности:
 * - скорость не может быть отрицательной;
 * - количество топлива не может быть отрицательным;
 * - двигатель не запускается без топлива;
 * - нельзя превысить объём топливного бака;
 * - скорость не может стать отрицательной.
 *
 * @return Код завершения программы.
 */
int main()
{
    /**
     * @brief [17][18] Первый объект.
     *
     * Создаётся конструктором без параметров.
     */
    Vehicle car1;

    /**
     * @brief [17][18] Второй объект.
     *
     * Создаётся параметризованным конструктором.
     */
    Vehicle car2("Toyota", 0, 30, 60, false);

    /**
     * @brief [17][18] Третий объект.
     *
     * Создаётся конструктором копирования.
     */
    Vehicle car3(car2);

    cout << "Количество объектов: "
         << Vehicle::getObjectCount() << "\n";

    /**
     * @brief [17] Проверка начального состояния объектов.
     */
    cout << "\n=== Начальное состояние ===\n";

    cout << "\nАвтомобиль 1:";
    car1.print();

    cout << "\nАвтомобиль 2:";
    car2.print();

    cout << "\nАвтомобиль 3:";
    car3.print();

    /**
     * @brief [12] Проверка осмысленных методов изменения состояния.
     *
     * Методы startEngine, accelerate, brake и refuel
     * выполняют реальные операции над состоянием автомобиля.
     */
    cout << "\n=== Корректные операции ===\n";

    car2.startEngine();
    car2.accelerate(50);
    car2.brake(20);
    car2.refuel(10);

    car2.print();

    /**
     * @brief [14] Проверка условий корректности при ошибочных операциях.
     */
    cout << "\n=== Некорректные операции ===\n";

    car1.accelerate(30);
    car2.refuel(100);
    car2.brake(-10);
    car2.accelerate(-20);

    /**
     * @brief [14] Проверка состояния после ошибочных операций.
     *
     * Состояние автомобиля не должно нарушать установленные условия.
     */
    cout << "\n=== Состояние после ошибок ===\n";

    car2.print();

    /**
     * @brief [19] Проверка независимости объектов.
     *
     * Изменение car1 не должно изменять car2 и car3.
     */
    cout << "\n=== Проверка независимости объектов ===\n";

    cout << "\nИзменяем car1...\n";

    car1.refuel(20);
    car1.startEngine();
    car1.accelerate(30);

    cout << "\nCar1:";
    car1.print();

    cout << "\nCar2:";
    car2.print();

    cout << "\nCar3:";
    car3.print();

    /**
     * @brief [21] Проверка количества существующих объектов.
     */
    cout << "\nКоличество объектов: "
         << Vehicle::getObjectCount() << "\n";

    return 0;
}